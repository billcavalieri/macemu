/*
 *  gen_expected.c - Runs every case in sb_cases.h on the build machine and prints sb_expected.h: the checksums the
 *  guest must reproduce. Built and run by guest/sheepbench/CMakeLists.txt with the build machine's compiler.
 *
 *  (C) 2026 Bill Cavalieri
 */

#include <stdio.h>
#include <stdlib.h>
#include "sb_cases.h"

int main(void)
{
    int i;
    printf("/* Generated by gen_expected.c from sb_cases.h: do not edit. */\n");
    printf("static const uint32_t kSbExpected[%d] = {\n", SB_NCASES);
    for (i = 0; i < SB_NCASES; i++) {
        const SbCase *c = &kSbCases[i];
        size_t n = sb_scratch_bytes(c->kernel, c->param);
        void *s = n ? malloc(n) : NULL;
        uint32_t sum;
        if (n && !s)
            return 1;
        sb_prepare(c->kernel, c->param, s);
        sum = sb_run(c->kernel, c->iters, c->param, s);
        printf("    0x%08xu,  /* kernel %u, %u iterations, param %u */\n", (unsigned)sum, (unsigned)c->kernel,
               (unsigned)c->iters, (unsigned)c->param);
        free(s);
    }
    printf("};\n");
    return 0;
}
